package com.aicommandcenter.app
fun main() {
    val shortcuts=IntegrationRules.defaults
    val all=shortcuts.first()
    val commands=listOf(Command("u","Universal","U"),Command("a","App","A",app="ai.chat"),Command("p","Project","P {{repo}}",project="p1"),Command("x","Other","X",app="ai.other"),Command("ap","App project","AP",app="ai.chat",project="p1"))
    fun resolve(target:String, app:String="ai.chat", project:String="p1")=IntegrationRules.resolve(commands,app,project,"owner/repo",target)
    check(IntegrationRules.validTrigger("#mpv"))
    check(IntegrationRules.validTrigger("#a-b_9"))
    check(!IntegrationRules.validTrigger("all"))
    check(!IntegrationRules.validTrigger("#"))
    check(!IntegrationRules.validTrigger("#a b"))
    check(!IntegrationRules.validTrigger("#"+"a".repeat(33)))
    check(IntegrationRules.find("#all;",shortcuts)==all)
    check(IntegrationRules.find("Draft\n#all;",shortcuts)==all)
    check(IntegrationRules.find("Draft #all;",shortcuts)==all)
    check(IntegrationRules.find("Draft#all;",shortcuts)==null)
    check(IntegrationRules.find("#all",shortcuts)==null)
    check(IntegrationRules.find("#all; ",shortcuts)==null)
    check(IntegrationRules.find("#missing;",shortcuts)==null)
    check(IntegrationRules.find("",shortcuts)==null)
    check(IntegrationRules.find("#all;",emptyList())==null)
    check(IntegrationRules.expand("Draft\n\n#all;",all,"U")=="Draft\n\nU")
    check(IntegrationRules.expand("#all;",all,"U")=="U")
    check(IntegrationRules.expand("Türkçe 😀 #all;",all,"指示")=="Türkçe 😀 \n\n指示")
    check(IntegrationRules.expand("#all;",all,"")==null)
    check(IntegrationRules.expand("#app;",all,"U")==null)
    check(resolve("ALL")=="Target GitHub repository: owner/repo\n\nU\n\nA\n\nP owner/repo\n\nAP")
    check(resolve("UNIVERSAL")=="Target GitHub repository: owner/repo\n\nU")
    check(resolve("APP")=="Target GitHub repository: owner/repo\n\nA")
    check(resolve("PROJECT")=="Target GitHub repository: owner/repo\n\nP owner/repo\n\nAP")
    check(resolve("command:ap")=="Target GitHub repository: owner/repo\n\nAP")
    check(resolve("command:ap",project="p2")=="")
    check(resolve("command:ap",app="ai.other")=="")
    check(resolve("command:x")=="")
    check(resolve("command:deleted")=="")
    check(resolve("nonsense")=="")
    check(IntegrationRules.resolve(commands,"ai.chat","",null,"ALL")=="U\n\nA")
    check(IntegrationRules.expand("Draft #all;",all,resolve("ALL"))=="Draft \n\n"+resolve("ALL"))
    println("PASS: integration-rule assertions")
}
