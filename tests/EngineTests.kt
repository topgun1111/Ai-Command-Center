package com.aicommandcenter.app
fun main() {
    val items=listOf(Command("p","Project","Project {{repo}} and {{repo_url}}",project="p1"),Command("a","App","App rules",app="ai.chat"),Command("u","Universal","Universal"),Command("ap","Specific","Specific",app="ai.chat",project="p1"),Command("x","Other","Other",app="ai.other",project="p1"),Command("y","Other project","Wrong project",project="p2"))
    fun ids(app:String,project:String,scope:Scope)=CommandEngine.matching(items,app,project,scope).map { it.id }
    check(ids("ai.chat","p1",Scope.ALL)==listOf("u","a","p","ap"))
    check(ids("ai.chat","p1",Scope.UNIVERSAL)==listOf("u"))
    check(ids("ai.chat","p1",Scope.APP)==listOf("a"))
    check(ids("ai.chat","p1",Scope.PROJECT)==listOf("p","ap"))
    check(ids("ai.chat","",Scope.ALL)==listOf("u","a"))
    check(ids("ai.other","p1",Scope.ALL)==listOf("u","p","x"))
    check(ids("","p1",Scope.ALL)==listOf("u","p"))
    check(ids("ai.chat","p2",Scope.ALL)==listOf("u","a","y"))
    check(CommandEngine.render(listOf(items.first()),"owner/repo")=="Target GitHub repository: owner/repo\n\nProject owner/repo and https://github.com/owner/repo")
    check(CommandEngine.render(listOf(items.first()),null)==items.first().body)
    check(CommandEngine.render(emptyList(),null)=="")
    check(CommandEngine.render(listOf(items[2],items[2]),null)=="Universal")
    check(CommandEngine.append("Draft","Rules")=="Draft\n\nRules")
    check(CommandEngine.append("Draft\n","Rules")=="Draft\n\nRules")
    check(CommandEngine.append("Draft\n\n","Rules")=="Draft\n\nRules")
    check(CommandEngine.append("Draft\n\nRules","Rules")=="Draft\n\nRules")
    check(CommandEngine.append("Rules","Rules")=="Rules")
    check(CommandEngine.append("Draft  ","Rules")=="Draft  \n\nRules")
    check(CommandEngine.append("","Rules")=="Rules")
    check(CommandEngine.append("Draft","  ")=="Draft")
    check(CommandEngine.append("Türkçe 😀","指示")=="Türkçe 😀\n\n指示")
    val long="x".repeat(100000); check(CommandEngine.append(long,long)==long)
    check(CommandEngine.validRepo("owner/pc-share_1.0"))
    check(!CommandEngine.validRepo("https://github.com/owner/repo"))
    check(!CommandEngine.validRepo("owner/.."))
    check(!CommandEngine.validRepo("owner/a/b"))
    check(!CommandEngine.validRepo("/repo"))
    check(!CommandEngine.validRepo("owner/"))
    check(CommandEngine.render(listOf(items[2]),"owner/repo")=="Target GitHub repository: owner/repo\n\nUniversal")
    check(CommandEngine.render(emptyList(),"owner/repo")=="")
    check(CommandEngine.render(listOf(Command("b","Blank","  ")),"owner/repo")=="")
    check(CommandEngine.render(listOf(items[2]),"owner/other")=="Target GitHub repository: owner/other\n\nUniversal")
    val block=CommandEngine.render(listOf(items[2],items[1]),"owner/repo")
    check(block=="Target GitHub repository: owner/repo\n\nUniversal\n\nApp rules")
    check(CommandEngine.append(CommandEngine.append("Draft",block),block)=="Draft\n\n$block")
    println("PASS: command-engine assertions")
}
